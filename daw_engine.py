class DAWMemory:
    """
    Project memory that tracks generation context for coherence.
    
    Stores what was generated before so that new parts can
    build on existing musical ideas.
    """
    
    def __init__(self):
        self.history: List[Dict] = []
        self.themes: Dict[str, List] = {}  # relation -> [generated info]
        self.active_keys: Dict[str, int] = {}  # track usage counts
    
    def record_part(self, part: DAWPart, audio_path: str, analysis: Dict):
        """Record a generated part in memory."""
        record = {
            'instrument': part.instrument,
            'relation': part.relation,
            'root': part.root,
            'scale': part.scale,
            'bpm': part.bpm,
            'measures': part.measures,
            'audio_path': audio_path,
            'analysis': analysis,
            'timestamp': datetime.now().isoformat(),
        }
        self.history.append(record)
        
        # Track by relation
        if part.relation not in self.themes:
            self.themes[part.relation] = []
        self.themes[part.relation].append(record)
        
        # Count instrument usage
        key = f"{part.instrument}_{part.relation}"
        self.active_keys[key] = self.active_keys.get(key, 0) + 1
    
    def get_context_for(self, part: DAWPart) -> str:
        """
        Build contextual description from memory for a new part.
        
        Tells MusicGen what already exists so it can blend in.
        """
        if not self.history:
            return ""
        
        context_parts = []
        
        # What's already playing in the project
        existing_instruments = set()
        for record in self.history:
            existing_instruments.add(record['instrument'])
        
        if existing_instruments:
            context_parts.append(
                f"Existing instruments: {', '.join(existing_instruments)}."
            )
        
        # Previous part in the same section
        same_relation = self.themes.get(part.relation, [])
        if same_relation:
            prev = same_relation[-1]
            context_parts.append(
                f"Previous {part.relation} had {prev['instrument']} "
                f"in {prev['root']} {prev['scale']} at {prev['bpm']} BPM."
            )
        
        # Overall project progress
        context_parts.append(
            f"This is part {len(self.history) + 1} in the project."
        )
        
        return " ".join(context_parts)
    
    def summary(self) -> str:
        """Get a summary of what's been generated."""
        lines = []
        lines.append(f"Total parts: {len(self.history)}")
        lines.append(f"Sections: {', '.join(self.themes.keys())}")
        for relation, records in self.themes.items():
            instrs = [r['instrument'] for r in records]
            lines.append(f"  {relation}: {', '.join(instrs)}")
        return "\n".join(lines)


