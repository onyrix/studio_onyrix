@dataclass
class PartEffect:
    """An effect applied to a part."""
    type: EffectType
    amount: float = 0.5  # 0.0 to 1.0
    params: Dict[str, float] = field(default_factory=dict)


@dataclass
class DAWTrack:
    """
    A mixer/timeline lane that can contain many generated parts.

    Parts are routed here by track_id so drums, bass, chords and leads
    can play at the same bar instead of becoming one long playlist.
    """
    id: str
    name: str
    instrument_class: str = "pad"
    volume: float = 1.0
    pan: float = 0.0
    muted: bool = False
    solo: bool = False
    effects: List[PartEffect] = field(default_factory=list)

    def to_dict(self) -> Dict:
        d = asdict(self)
        d['effects'] = [asdict(e) for e in self.effects]
        return d


@dataclass
class DAWPart:
    """
    A single instrument part in the DAW project.
    
    This is the fundamental building block of a project.
    Each part represents one instrument playing for a
    specific number of measures with precise musical parameters.
    """
    # Musical parameters
    bpm: int = 120
    division: str = "4/4"
    root: str = "C"
    scale: str = "natural_minor"
    measures: int = 8
    
    # Instrument
    instrument: str = "synth_pad"
    instrument_class: str = "pad"
    
    # Arrangement
    relation: str = "verse"
    order: int = 0  # Position in project
    track_id: str = ""
    start_bar: float = 1.0
    
    # Mixing
    volume: float = 0.8      # 0.0 to 1.0
    pan: float = 0.0         # -1.0 (left) to 1.0 (right)
    effects: List[PartEffect] = field(default_factory=list)
    
    # AI generation
    extra_prompt: str = ""
    temperature: float = 1.0
    top_k: int = 250
    cfg_coef: float = 3.0
    
    # Auto-generated
    id: str = ""
    timestamp: str = ""
    
    # Results (filled after generation)
    audio_path: str = ""
    duration: float = 0.0
    analysis: Dict = field(default_factory=dict)
    
    def __post_init__(self):
        if not self.id:
            self.id = f"{self.instrument}_{self.relation}_{datetime.now().strftime('%H%M%S')}"
        if not self.timestamp:
            self.timestamp = datetime.now().isoformat()
    
    @property
    def beats_per_measure(self) -> float:
        """Get measure length in quarter-note beats from division string."""
        return _division_to_quarter_beats(self.division)
    
    @property
    def total_beats(self) -> float:
        """Total beats for this part."""
        return self.measures * self.beats_per_measure
    
    @property
    def duration_seconds(self) -> float:
        """Calculate duration in seconds based on BPM and measures."""
        return (self.total_beats / self.bpm) * 60.0

    @property
    def end_bar(self) -> float:
        """One-based bar where this part ends."""
        return self.start_bar + self.measures
    
    @property
    def scale_notes(self) -> List[str]:
        """Get note names in this part's scale."""
        root_idx = NOTE_NAMES.index(self.root)
        pattern = SCALE_PATTERNS.get(self.scale, SCALE_PATTERNS["natural_minor"])
        return [NOTE_NAMES[(root_idx + i) % 12] for i in pattern]
    
    def to_dict(self) -> Dict:
        """Serialize to dictionary."""
        d = asdict(self)
        d['effects'] = [asdict(e) for e in self.effects]
        return d
    
    def build_prompt(self) -> str:
        """
        Build a precise, musician-focused prompt for MusicGen.
        
        This is the key innovation - instead of a vague prompt,
        we build a detailed musical specification that tells
        MusicGen exactly what to generate.
        """
        instrument_info = INSTRUMENT_PRESETS.get(self.instrument, {})
        instr_desc = instrument_info.get("description", self.instrument)
        instr_class = instrument_info.get("class", self.instrument_class)
        register = instrument_info.get("register", "mid")
        
        # Get scale info
        scale_notes_str = ", ".join(self.scale_notes)
        
        # Build relational context
        context_descriptions = {
            "intro": "introduction, establishing the mood",
            "verse": "verse section, supporting the narrative",
            "chorus": "chorus section, energetic and memorable",
            "bridge": "bridge section, contrasting and emotional",
            "drop": "drop section, maximum energy",
            "build": "build up section, rising tension",
            "fill": "fill section, transitional",
            "outro": "outro section, fading out",
            "transition": "transition section, connecting parts",
            "solo": "solo section, featured instrument",
        }
        context = context_descriptions.get(self.relation, self.relation)
        
        # Build the prompt
        prompt_parts = [
            f"Generate a {instr_desc} part for music production.",
            f"Time signature: {self.division}.",
            f"Tempo: {self.bpm} BPM.",
            f"Length: {self.measures} bars ({self.duration_seconds:.1f} seconds).",
            f"Timeline position: starts at bar {self.start_bar:g}.",
            f"Key: {self.root} {self.scale.replace('_', ' ')}.",
            f"Scale notes: {scale_notes_str}.",
            f"Section: {context}.",
            f"Instrument register: {register}.",
        ]
        
        if self.extra_prompt:
            prompt_parts.append(f"Style: {self.extra_prompt}.")
        
        return " ".join(prompt_parts)
    
    def validate(self) -> List[str]:
        """Validate part parameters, return list of warnings."""
        warnings = []
        
        if self.bpm < 30 or self.bpm > 300:
            warnings.append(f"Unusual BPM: {self.bpm}")
        
        if self.root not in NOTE_NAMES:
            warnings.append(f"Invalid root note: {self.root}")
        
        if self.scale not in SCALE_PATTERNS:
            warnings.append(f"Unknown scale: {self.scale}")
        
        if self.measures < 1:
            warnings.append(f"Measures must be >= 1, got {self.measures}")

        if self.start_bar < 1:
            warnings.append(f"Start bar must be >= 1, got {self.start_bar}")
        
        if self.volume < 0.0 or self.volume > 1.0:
            warnings.append(f"Volume must be 0-1, got {self.volume}")
        
        if self.pan < -1.0 or self.pan > 1.0:
            warnings.append(f"Pan must be -1 to 1, got {self.pan}")
        
        return warnings


@dataclass
class DAWProject:
    """
    A complete music production project.
    
    Manages multiple DAWPart instances with:
    - Project-level key/scale (all parts inherit by default)
    - Mixing (volume, pan per part)
    - Timeline (order of parts)
    - Project file save/load
    """
    name: str = "Untitled"
    schema_version: str = "0.5"
    bpm: int = 120
    division: str = "4/4"
    root: str = "C"
    scale: str = "natural_minor"
    parts: List[DAWPart] = field(default_factory=list)
    tracks: List[DAWTrack] = field(default_factory=list)
    chord_progression: List[str] = field(default_factory=list)
    groove: str = "straight"
    swing: float = 0.0
    style_tags: List[str] = field(default_factory=list)
    description: str = ""
    master_volume: float = 1.0
    master_effects: List[PartEffect] = field(default_factory=list)
    render_settings: Dict[str, Any] = field(default_factory=dict)
    memory: Dict[str, Any] = field(default_factory=dict)
    created: str = ""
    modified: str = ""
    project_dir: str = ""
    
    def __post_init__(self):
        now = datetime.now()
        if not self.created:
            self.created = now.isoformat()
        self.modified = now.isoformat()
        if not self.tracks:
            self._create_default_tracks()
        if not self.render_settings:
            self.render_settings = {
                "sample_rate": 32000,
                "channels": 2,
                "format": "wav",
                "bit_depth": "float32",
            }
        if not self.memory:
            self.memory = self._empty_memory()

    def _empty_memory(self) -> Dict[str, Any]:
        """Persistent creative memory for AI generation and future UI state."""
        return {
            "intent": "",
            "references": [],
            "generation_history": [],
            "motifs": [],
            "sections": {},
            "instrument_roles": {},
            "warnings": [],
        }

    def _create_default_tracks(self):
        """Create the basic lanes a musician expects in a session."""
        self.tracks = [
            DAWTrack(id="drums", name="Drums", instrument_class="drums", volume=1.0),
            DAWTrack(id="bass", name="Bass", instrument_class="bass", volume=0.9),
            DAWTrack(id="chords", name="Chords", instrument_class="chords", volume=0.8),
            DAWTrack(id="lead", name="Lead", instrument_class="lead", volume=0.85),
            DAWTrack(id="fx", name="FX", instrument_class="fx", volume=0.8),
        ]

    def beats_per_bar(self) -> float:
        return _division_to_quarter_beats(self.division)

    def bar_to_seconds(self, bar: float) -> float:
        """Convert a one-based bar number to seconds from project start."""
        return max(0.0, (bar - 1.0) * self.beats_per_bar() * 60.0 / self.bpm)

    def generation_context(self) -> str:
        """Project-wide musical constraints for AI prompt coherence."""
        context = [
            f"Project tempo is {self.bpm} BPM.",
            f"Project key is {self.root} {self.scale.replace('_', ' ')}.",
            f"Project groove is {self.groove}.",
        ]
        if self.swing > 0:
            context.append(f"Use about {self.swing:.0%} swing feel.")
        if self.chord_progression:
            context.append(
                f"Follow this chord progression: {' - '.join(self.chord_progression)}."
            )
        return " ".join(context)

    def find_track(self, track_id: str) -> Optional[DAWTrack]:
        for track in self.tracks:
            if track.id == track_id:
                return track
        return None

    def add_track(self, name: str, instrument_class: str = "pad",
                  track_id: Optional[str] = None) -> DAWTrack:
        """Add a track if it does not already exist."""
        clean_id = track_id or name.lower().strip().replace(" ", "_")
        existing = self.find_track(clean_id)
        if existing:
            return existing

        track = DAWTrack(id=clean_id, name=name, instrument_class=instrument_class)
        self.tracks.append(track)
        self.modified = datetime.now().isoformat()
        return track

    def route_for_part(self, part: DAWPart) -> DAWTrack:
        """Find or create the right track lane for a part."""
        if part.track_id:
            track = self.find_track(part.track_id)
            if track:
                return track

        class_to_track = {
            "drums": "drums",
            "percussion": "drums",
            "bass": "bass",
            "chords": "chords",
            "pad": "chords",
            "arpeggio": "chords",
            "melody": "lead",
            "lead": "lead",
            "vocals": "lead",
            "fx": "fx",
        }
        track_id = class_to_track.get(part.instrument_class, part.instrument_class)
        track = self.find_track(track_id)
        if not track:
            track = self.add_track(track_id.title(), part.instrument_class, track_id)
        part.track_id = track.id
        return track
    
    def add_part(self, part: DAWPart) -> int:
        """
        Add a part to the project.
        Returns the index of the added part.
        """
        # Inherit project defaults if not specified
        if part.bpm == 120 and self.bpm != 120:
            part.bpm = self.bpm
        if part.division == "4/4" and self.division != "4/4":
            part.division = self.division
        if part.root == "C" and self.root != "C":
            part.root = self.root
        if part.scale == "natural_minor" and self.scale != "natural_minor":
            part.scale = self.scale

        self.route_for_part(part)
        
        part.order = len(self.parts)
        self.parts.append(part)
        self.modified = datetime.now().isoformat()
        return len(self.parts) - 1
    
    def remove_part(self, index: int) -> Optional[DAWPart]:
        """Remove a part by index."""
        if 0 <= index < len(self.parts):
            part = self.parts.pop(index)
            # Re-index remaining parts
            for i, p in enumerate(self.parts):
                p.order = i
            self.modified = datetime.now().isoformat()
            return part
        return None
    
    def get_part(self, index: int) -> Optional[DAWPart]:
        """Get a part by index."""
        if 0 <= index < len(self.parts):
            return self.parts[index]
        return None
    
    @property
    def total_duration(self) -> float:
        """Calculate total duration of all parts (worst case)."""
        max_end = 0
        for part in self.parts:
            end = self.bar_to_seconds(part.end_bar)
            max_end = max(max_end, end)
        return max_end

    def audio_assets(self) -> List[Dict[str, Any]]:
        """Collect render assets referenced by parts without embedding audio data."""
        assets = []
        for part in self.parts:
            if not part.audio_path:
                continue
            assets.append({
                "id": f"audio_{part.id}",
                "part_id": part.id,
                "track_id": part.track_id,
                "path": part.audio_path,
                "type": "audio",
                "format": os.path.splitext(part.audio_path)[1].lstrip(".") or "wav",
                "duration_seconds": part.duration or part.duration_seconds,
                "sample_rate": self.render_settings.get("sample_rate", 32000),
            })
        return assets

    def midi_assets(self) -> List[Dict[str, Any]]:
        """Placeholder for v0.5+ MIDI clips once note generation is improved."""
        assets = []
        for part in self.parts:
            midi_path = part.analysis.get("midi_path") if isinstance(part.analysis, dict) else None
            if not midi_path:
                continue
            assets.append({
                "id": f"midi_{part.id}",
                "part_id": part.id,
                "track_id": part.track_id,
                "path": midi_path,
                "type": "midi",
                "format": "mid",
            })
        return assets

    def record_generation(self, part: DAWPart, prompt: str,
                          audio_path: str = "", analysis: Optional[Dict] = None,
                          warnings: Optional[List[str]] = None):
        """Persist AI generation memory inside the project JSON."""
        if not self.memory:
            self.memory = self._empty_memory()

        event = {
            "timestamp": datetime.now().isoformat(),
            "part_id": part.id,
            "track_id": part.track_id,
            "instrument": part.instrument,
            "instrument_class": part.instrument_class,
            "relation": part.relation,
            "start_bar": part.start_bar,
            "measures": part.measures,
            "prompt": prompt,
            "audio_path": audio_path,
            "analysis": analysis or {},
            "warnings": warnings or [],
        }
        self.memory.setdefault("generation_history", []).append(event)
        self.memory.setdefault("sections", {}).setdefault(part.relation, []).append(part.id)
        self.memory.setdefault("instrument_roles", {})[part.track_id] = {
            "instrument": part.instrument,
            "class": part.instrument_class,
            "role": part.relation,
        }
        if warnings:
            self.memory.setdefault("warnings", []).extend(warnings)
        self.modified = datetime.now().isoformat()

    def to_project_document(self) -> Dict[str, Any]:
        """
        Export the v0.5 source-of-truth document for the future DAW UI.

        This is intentionally more explicit than the dataclasses: UI code should
        be able to reconstruct transport, musical intent, timeline and assets
        without knowing Python internals.
        """
        modified = datetime.now().isoformat()
        return {
            "schema_version": self.schema_version,
            "application": "Studio Onyrix",
            "project": {
                "name": self.name,
                "description": self.description,
                "style_tags": self.style_tags,
                "created": self.created,
                "modified": modified,
            },
            "transport": {
                "bpm": self.bpm,
                "division": self.division,
                "beats_per_bar": self.beats_per_bar(),
                "duration_seconds": self.total_duration,
            },
            "musical_context": {
                "root": self.root,
                "scale": self.scale,
                "scale_notes": [
                    NOTE_NAMES[(NOTE_NAMES.index(self.root) + i) % 12]
                    for i in SCALE_PATTERNS.get(self.scale, SCALE_PATTERNS["natural_minor"])
                ] if self.root in NOTE_NAMES else [],
                "chord_progression": self.chord_progression,
                "groove": self.groove,
                "swing": self.swing,
            },
            "render_settings": self.render_settings,
            "master": {
                "volume": self.master_volume,
                "effects": [asdict(e) for e in self.master_effects],
            },
            "tracks": [t.to_dict() for t in self.tracks],
            "parts": [p.to_dict() for p in self.parts],
            "assets": {
                "audio": self.audio_assets(),
                "midi": self.midi_assets(),
            },
            "memory": self.memory or self._empty_memory(),
        }
    
    def save(self, filepath: str):
        """Save project to JSON file."""
        data = self.to_project_document()
        
        with open(filepath, 'w') as f:
            json.dump(data, f, indent=2, default=str)
        
        self.modified = datetime.now().isoformat()
        print(f"Project saved: {filepath}")
    
    @classmethod
    def load(cls, filepath: str) -> 'DAWProject':
        """Load project from JSON file."""
        with open(filepath, 'r') as f:
            data = json.load(f)
        
        schema_version = data.get('schema_version', '0.4')
        proj_data = data.get('project', {})
        transport = data.get('transport', proj_data)
        musical_context = data.get('musical_context', proj_data)
        master = data.get('master', {})

        def decode_effects(raw_effects: List[Dict[str, Any]]) -> List[PartEffect]:
            effects = []
            for ef in raw_effects:
                effect_type = ef.get('type', EffectType.REVERB)
                effects.append(PartEffect(
                    type=EffectType(effect_type),
                    amount=ef.get('amount', 0.5),
                    params=ef.get('params', {}),
                ))
            return effects

        project = cls(
            name=proj_data.get('name', 'Untitled'),
            schema_version=schema_version,
            bpm=transport.get('bpm', 120),
            division=transport.get('division', '4/4'),
            root=musical_context.get('root', 'C'),
            scale=musical_context.get('scale', 'natural_minor'),
            chord_progression=musical_context.get('chord_progression', []),
            groove=musical_context.get('groove', 'straight'),
            swing=musical_context.get('swing', 0.0),
            style_tags=proj_data.get('style_tags', []),
            description=proj_data.get('description', ''),
            master_volume=master.get('volume', 1.0),
            master_effects=decode_effects(master.get('effects', [])),
            render_settings=data.get('render_settings', {}),
            memory=data.get('memory', {}),
            created=proj_data.get('created', ''),
            project_dir=os.path.dirname(filepath),
        )

        if data.get('tracks'):
            project.tracks = []
            for track_data in data['tracks']:
                track_data = dict(track_data)
                track_data['effects'] = decode_effects(track_data.get('effects', []))
                project.tracks.append(DAWTrack(**track_data))
        
        for part_data in data.get('parts', []):
            part_data = dict(part_data)
            part_data['effects'] = decode_effects(part_data.pop('effects', []))
            part = DAWPart(**part_data)
            project.route_for_part(part)
            project.parts.append(part)
        
        print(f"Project loaded: {filepath}")
        print(f"  Parts: {len(project.parts)}")
        print(f"  BPM: {project.bpm}, Key: {project.root} {project.scale}")
        return project


