def create_intro_part(bpm: int = 100, root: str = "C", scale: str = "major") -> DAWPart:
    """Create a typical intro part."""
    return DAWPart(
        bpm=bpm, root=root, scale=scale,
        instrument="texture_pad", instrument_class="pad",
        measures=4, relation="intro",
        volume=0.5, temperature=0.8,
        extra_prompt="atmospheric, building anticipation, sparse",
    )

def create_drum_part(bpm: int = 140, style: str = "trap_drums", measures: int = 8) -> DAWPart:
    """Create a drum part."""
    return DAWPart(
        bpm=bpm, root="C", scale="chromatic",
        instrument=style, instrument_class="drums",
        measures=measures, relation="verse",
        volume=0.9, temperature=0.7,
        extra_prompt="consistent groove, good energy",
    )

def create_bass_part(bpm: int = 140, root: str = "C", scale: str = "natural_minor",
                     style: str = "808_bass", measures: int = 8) -> DAWPart:
    """Create a bass part following the key."""
    return DAWPart(
        bpm=bpm, root=root, scale=scale,
        instrument=style, instrument_class="bass",
        measures=measures, relation="verse",
        volume=0.8, temperature=0.6,
        extra_prompt=f"follow {root} {scale} scale, solid root notes",
    )

def create_chord_part(bpm: int = 140, root: str = "C", scale: str = "natural_minor",
                      style: str = "synth_pad", measures: int = 8) -> DAWPart:
    """Create a chord/pad part."""
    return DAWPart(
        bpm=bpm, root=root, scale=scale,
        instrument=style, instrument_class="pad",
        measures=measures, relation="chorus",
        volume=0.6, temperature=0.9,
        extra_prompt=f"warm chords in {root} {scale}, sustained",
    )

def create_melody_part(bpm: int = 140, root: str = "C", scale: str = "natural_minor",
                       style: str = "synth_lead", measures: int = 8) -> DAWPart:
    """Create a melody/lead part."""
    return DAWPart(
        bpm=bpm, root=root, scale=scale,
        instrument=style, instrument_class="lead",
        measures=measures, relation="chorus",
        volume=0.7, temperature=1.2,  # Higher temp for more creative melodies
        extra_prompt=f"catchy melody in {root} {scale}, expressive",
    )


