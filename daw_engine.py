class DAWPartGenerator:
    """
    Generates audio for a single DAWPart using MusicGen.
    
    Key features:
    - Builds precise prompts from musical parameters
    - Maintains memory for project coherence
    - Extracts audio analysis (tempo, beats, keys)
    - Validates generated audio against specifications
    """
    
    def __init__(self, model_size: str = 'small'):
        self.musicgen = MusicGenGenerator(model_size=model_size)
        self.analyzer = AudioAnalyzer() if MUSICGEN_AVAILABLE else None
        self.memory = DAWMemory()
        self.generation_count = 0
        
        print(f"\n{'='*60}")
        print("DAW Part Generator Status:")
        print(f"  MusicGen: {'READY' if self.musicgen.available else 'NOT INSTALLED'}")
        print(f"  Audio Analysis: {'READY' if (self.analyzer and self.analyzer.available) else 'NOT AVAILABLE'}")
        print(f"{'='*60}\n")
    
    def generate_part(self, part: DAWPart, output_dir: str = "output",
                      project: Optional[DAWProject] = None) -> Dict:
        """
        Generate audio for a single part.
        
        Args:
            part: The DAWPart to generate
            output_dir: Where to save the audio file
        
        Returns:
            Dict with keys: 'audio', 'analysis', 'path', 'success'
        """
        result = {
            'audio': None,
            'analysis': {},
            'path': '',
            'success': False,
            'warnings': [],
        }
        
        # Validate
        warnings = part.validate()
        if warnings:
            result['warnings'] = warnings
            for w in warnings:
                print(f"  Warning: {w}")
        
        if not self.musicgen.available:
            print("MusicGen not available. Install transformers and torchaudio.")
            return result
        
        # Build prompt with context from memory
        prompt = part.build_prompt()
        context = self.memory.get_context_for(part)
        project_context = project.generation_context() if project else ""
        if context or project_context:
            full_prompt = " ".join(p for p in [prompt, project_context, context] if p)
        else:
            full_prompt = prompt
        
        print(f"\n{'='*50}")
        print(f"Generating Part: {part.id}")
        print(f"  Instrument: {part.instrument}")
        print(f"  BPM: {part.bpm} | Division: {part.division}")
        print(f"  Key: {part.root} {part.scale}")
        print(f"  Measures: {part.measures} ({part.duration_seconds:.1f}s)")
        print(f"  Relation: {part.relation}")
        print(f"  Track: {part.track_id or '-'} | Start bar: {part.start_bar:g}")
        print(f"  Pitch/Temperature: {part.temperature}")
        print(f"  Prompt: {prompt}")
        if project_context:
            print(f"  Project: {project_context}")
        if context:
            print(f"  Context: {context}")
        print(f"{'='*50}")
        
        # Generate audio
        audio = self.musicgen.generate(
            prompt=full_prompt,
            duration=int(part.duration_seconds) + 1,  # Add 1s buffer
            temperature=part.temperature,
            top_k=part.top_k,
            cfg_coef=part.cfg_coef,
        )
        
        if audio is None:
            print("Generation failed.")
            return result
        
        # Trim to exact duration
        expected_samples = int(part.duration_seconds * 32000)
        if audio.shape[-1] > expected_samples:
            if audio.ndim == 2:
                audio = audio[:, :expected_samples]
            else:
                audio = audio[:expected_samples]
        
        result['audio'] = audio
        
        # Analyze
        if self.analyzer and self.analyzer.available:
            result['analysis'] = self.analyzer.analyze(audio)
            part.analysis = result['analysis']
            
            # Check if tempo matches
            if 'tempo' in result['analysis']:
                detected_bpm = result['analysis']['tempo']
                ratio = detected_bpm / part.bpm
                if ratio < 0.5 or ratio > 2.0:
                    result['warnings'].append(
                        f"Detected tempo ({detected_bpm:.0f} BPM) differs significantly "
                        f"from requested ({part.bpm} BPM). Consider adjusting."
                    )
        
        # Save audio
        part.audio_path = self._save_audio(audio, part, output_dir)
        result['path'] = part.audio_path
        part.duration = audio.shape[-1] / 32000
        
        # Record in memory
        self.memory.record_part(part, part.audio_path, result['analysis'])
        if project:
            project.record_generation(
                part=part,
                prompt=full_prompt,
                audio_path=part.audio_path,
                analysis=result['analysis'],
                warnings=result['warnings'],
            )
        self.generation_count += 1
        
        result['success'] = True
        print(f"\n✓ Part generated: {part.audio_path}")
        print(f"  Duration: {part.duration:.1f}s")
        
        return result
    
    def _save_audio(self, audio: np.ndarray, part: DAWPart, output_dir: str) -> str:
        """Save generated audio to file."""
        os.makedirs(output_dir, exist_ok=True)
        
        filename = f"{part.id}_{datetime.now().strftime('%H%M%S')}.wav"
        filepath = os.path.join(output_dir, filename)
        
        if audio.ndim == 2:
            audio_for_sf = audio.T if audio.shape[0] <= 2 else audio
        else:
            audio_for_sf = audio
        
        sf.write(filepath, audio_for_sf, 32000)
        return filepath
    
    def generate_replacement(self, part_index: int, new_part: DAWPart, 
                            output_dir: str = "output") -> Dict:
        """
        Generate a replacement for an existing part.
        Removes old part from memory and generates new one.
        """
        # Since we can't easily remove from memory history,
        # we just generate the new part with context of everything else
        return self.generate_part(new_part, output_dir)
    
    def validate_project_coherence(self, project: DAWProject) -> List[str]:
        """Check if all parts in a project are musically coherent."""
        issues = []
        
        if not project.parts:
            return issues
        
        # Check key consistency
        roots = set(p.root for p in project.parts)
        if len(roots) > 1:
            issues.append(f"Multiple keys detected: {roots}")
        
        # Check BPM consistency
        bpms = set(p.bpm for p in project.parts)
        if len(bpms) > 1:
            issues.append(f"Multiple BPMs detected: {bpms}. Ensure they match.")
        
        return issues


