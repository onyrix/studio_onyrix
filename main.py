def cmd_save(args):
    """Save project to file."""
    filepath = args[0] if args else PROJECT_FILE
    os.makedirs("output", exist_ok=True)
    if not filepath.startswith("output"):
        filepath = os.path.join("output", filepath)
    CURRENT_PROJECT.save(filepath)


def cmd_load(args):
    """Load project from file."""
    global CURRENT_PROJECT
    if not args:
        print("Usage: main.py load <filepath>")
        return
    filepath = args[0]
    if not os.path.exists(filepath):
        filepath = os.path.join("output", filepath)
    if os.path.exists(filepath):
        CURRENT_PROJECT = DAWProject.load(filepath)
    else:
        print(f"File not found: {filepath}")


def cmd_generate_all(args):
    """Generate all parts that don't have audio yet."""
    generator = get_generator()
    if not generator.musicgen.available:
        print("MusicGen not available.")
        return
    
    for i, part in enumerate(CURRENT_PROJECT.parts):
        if part.audio_path and os.path.exists(part.audio_path):
            print(f"  [{i}] Already generated, skipping: {part.instrument}")
            continue
        
        print(f"\n  [{i}] Generating: {part.instrument} ({part.relation})...")
        result = generator.generate_part(part, project=CURRENT_PROJECT)
        if result['success']:
            print(f"    ✓ Audio saved")
        else:
            print(f"    ✗ Failed")
    
    save_project()


