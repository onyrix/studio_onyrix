def cmd_interactive(args):
    """Enter interactive mode."""
    print(f"\n{'='*60}")
    print("Studio Onyrix - Interactive Mode")
    print(f"{'='*60}")
    print("Type 'help' for commands, 'exit' to quit.")
    
    while True:
        try:
            cmd = input(f"\n[{CURRENT_PROJECT.name}] > ").strip()
            if not cmd:
                continue
            
            parts = cmd.split()
            command = parts[0]
            cmd_args = parts[1:]
            
            if command in ('exit', 'quit', 'q'):
                save_project()
                print("Project saved. Goodbye!")
                break
            
            elif command == 'help':
                print_help()
            
            elif command == 'new':
                cmd_new_project(cmd_args)
            
            elif command == 'add':
                cmd_add_part(cmd_args)
            
            elif command == 'list':
                cmd_list_parts(cmd_args)
            
            elif command == 'remove':
                cmd_remove_part(cmd_args)
            
            elif command == 'info':
                cmd_info(cmd_args)
            
            elif command == 'mix':
                cmd_mix(cmd_args)
            
            elif command == 'instruments':
                cmd_instruments(cmd_args)
            
            elif command == 'scales':
                cmd_scales(cmd_args)

            elif command == 'tracks':
                cmd_tracks(cmd_args)

            elif command in ('arrangement', 'song'):
                cmd_arrangement(cmd_args)
            
            elif command == 'save':
                cmd_save(cmd_args)
            
            elif command == 'load':
                cmd_load(cmd_args)
            
            elif command == 'generate':
                cmd_generate_all(cmd_args)
            
            elif command == 'show':
                cmd_show(cmd_args)
            
            else:
                print(f"Unknown command: {command}")
                print("Type 'help' for available commands")
                
        except KeyboardInterrupt:
            print("\n")
            save_project()
            print("Project saved. Goodbye!")
            break
        except Exception as e:
            print(f"Error: {e}")
            import traceback
            traceback.print_exc()


