CURRENT_PROJECT = DAWProject(name="Untitled", bpm=120, root="C", scale="natural_minor")
PROJECT_FILE = "output/project.json"
GENERATOR = None  # Lazy initialized


def get_generator() -> DAWPartGenerator:
    """Get or initialize the DAW part generator."""
    global GENERATOR
    if GENERATOR is None:
        print("Initializing DAW Part Generator...")
        GENERATOR = DAWPartGenerator(model_size='small')
    return GENERATOR


def ensure_project_loaded():
    """Load project if exists."""
    global CURRENT_PROJECT
    if os.path.exists(PROJECT_FILE):
        try:
            CURRENT_PROJECT = DAWProject.load(PROJECT_FILE)
            print(f"Loaded project: {CURRENT_PROJECT.name}")
        except Exception:
            CURRENT_PROJECT = DAWProject(name="Untitled", bpm=120, root="C", scale="natural_minor")


def save_project():
    """Save current project to default location."""
    os.makedirs("output", exist_ok=True)
    CURRENT_PROJECT.save(PROJECT_FILE)


